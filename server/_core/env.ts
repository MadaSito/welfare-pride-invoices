export const ENV = {
  get databaseUrl() { return process.env.DATABASE_URL ?? ""; },
  get isProduction() { return process.env.NODE_ENV === "production"; },
  get appOrigin() { return (process.env.APP_ORIGIN ?? "").replace(/\/$/, ""); },
  get trustProxy() { return process.env.TRUST_PROXY === "true" || process.env.TRUST_PROXY === "1"; },
  get entraTenantId() { return process.env.ENTRA_TENANT_ID ?? ""; },
  get entraClientId() { return process.env.ENTRA_CLIENT_ID ?? ""; },
  get entraClientSecret() { return process.env.ENTRA_CLIENT_SECRET ?? ""; },
  get schedulerSecret() { return process.env.RECURRING_SCHEDULER_SECRET ?? ""; },
  get s3Endpoint() { return process.env.S3_ENDPOINT ?? ""; },
  get s3Region() { return process.env.S3_REGION ?? "us-east-1"; },
  get s3Bucket() { return process.env.S3_BUCKET ?? ""; },
  get s3AccessKeyId() { return process.env.S3_ACCESS_KEY_ID ?? ""; },
  get s3SecretAccessKey() { return process.env.S3_SECRET_ACCESS_KEY ?? ""; },
  get s3PublicBaseUrl() { return (process.env.S3_PUBLIC_BASE_URL ?? "").replace(/\/$/, ""); },
};
